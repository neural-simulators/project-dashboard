    body = json.dumps(r4(sample), indent=1, sort_keys=True, allow_nan=False)
    text = HEADER.format(a=manifest["scene_id"], b=manifest8["scene_id"], job=JOB["id"]) + "window.POST_TRAINING_DATA = " + body + ";\n"
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print("wrote %s (%d bytes): %d samples, group mean %.3f std %.3f, pair gap %.2f, base eval %d/%d PhysX passes" % (
        out, len(text.encode("utf-8")), len(samples), mean, std, pair["reward_gap"], results["base_eval"]["physx_pass"], results["base_eval"]["cases"]))
    return 0


