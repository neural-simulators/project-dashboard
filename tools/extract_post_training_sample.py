def plain_goal(req, labels, containers):
    name = lambda key: labels.get(key, key)
    kind = req["kind"]
    if kind == "no_contact":
        return "the %s never touches the %s" % (name(req["object_ids"][0]), name(req["object_ids"][1]))
    if kind == "end_region":
        for c in containers:
            interior = c.get("interior_bounds_world_m")
            if interior and all(abs(a - b) < 1e-6 for a, b in zip(interior["min"] + interior["max"], req["bounds_min"] + req["bounds_max"])):
                return "the %s ends inside the %s" % (name(req["object_id"]), c["label"])
        return "the %s ends inside the marked zone" % name(req["object_id"])
    if kind == "speed":
        return "the %s is at rest at 2 s (under %.2f m/s)" % (name(req["object_id"]), req["max_speed_m_s"])
    if kind == "contact_deadline":
        return "the %s hits the %s within %.1f s" % (name(req["object_ids"][0]), name(req["object_ids"][1]), req["deadline_s"])
    if kind == "displacement":
        return "the %s moves at least %.0f cm" % (name(req["object_id"]), 100 * req["min_distance_m"])
    if kind == "ordered_contacts":
        steps = ["the %s" % name(pair[1]) for pair in req["pairs"]]
        return "the %s touches %s first, then %s, within %.0f s" % (name(req["pairs"][0][0]), steps[0], ", then ".join(steps[1:]), req["deadline_s"])
    return kind.replace("_", " ")


def launch_why(rows, labels, trajectories, goals):
    lines = []
    for row in rows:
        if row["passed"]:
            continue
        req, meas = row["requirement"], row.get("measurements", {})
        kind = req["kind"]
        if kind == "end_region":
            box_min, box_max = meas.get("body_world_aabb_min"), meas.get("body_world_aabb_max")
            if box_min and box_max:
                cx = (box_min[0] + box_max[0]) / 2
                edge = req["bounds_min"][0] if cx < req["bounds_min"][0] else req["bounds_max"][0]
                lines.append("the %s stops at x = %.2f m, %.2f m %s the target zone" % (labels.get(req["object_id"]), cx, abs(cx - edge),
                             "short of" if cx < req["bounds_min"][0] else "beyond"))
            else:
                lines.append("the %s does not end in the target zone" % labels.get(req["object_id"]))
        elif kind == "contact_deadline":
            lines.append("the %s does not reach the %s within %.1f s" % (labels.get(req["object_ids"][0]), labels.get(req["object_ids"][1]), req["deadline_s"]))
        elif kind == "displacement":
            lines.append("the %s moves too little" % labels.get(req["object_id"]))
        elif kind == "speed":
            lines.append("the %s is still moving at 2 s (%.2f m/s)" % (labels.get(req["object_id"]), meas.get("final_linear_speed_m_s", 0)))
        elif kind == "no_contact":
            lines.append("the %s touches the %s" % (labels.get(req["object_ids"][0]), labels.get(req["object_ids"][1])))
        elif kind == "ordered_contacts":
            lines.append("the contacts happen in the wrong order or not at all")
        else:
            lines.append("goal '%s' not met" % kind)
    return lines


def launch_reward(rows, verdict_pass, contract=True):
    if not contract:
        return 0.1
    fraction = sum(bool(r["passed"]) for r in rows) / len(rows) if rows else 0.
    return 0.1 + 0.2 + 0.4 * fraction + 0.3 * (1. if verdict_pass else 0.)


def trajectories(reference, movable):
    """[x, z] per sampled frame for every movable object that moves more than 1 cm."""
    out = {}
    for key in movable:
        path = []
        for state in reference["states"]:
            match = [o for o in state["objects"] if o["id"] == key]
            if match:
                path.append([match[0]["position"][0], match[0]["position"][2]])
        if path and max(math.hypot(p[0] - path[0][0], p[1] - path[0][1]) for p in path) > .01:
            out[key] = path
    return out


