def static_explanations(diagnostics, labels):
    """Plain-language lines for every failed check, with the measured number."""
    lines = []
    for row in diagnostics["instruction"]["predicates"]:
        if not row["passed"]:
            kind, pred, meas = row["predicate"]["kind"], row["predicate"], row.get("measurements", {})
            name = labels.get(pred.get("object_id"), pred.get("object_id"))
            if kind == "supported_by":
                lines.append("the %s is not resting on the %s" % (name, labels.get(pred.get("support_id"), "support")))
            elif kind == "face":
                lines.append("the %s does not face the %s (%.0f degrees off, limit 15)" % (name, labels.get(pred.get("target_id"), "target"), meas.get("angle_deg", 0)))
            elif kind == "closer":
                lines.append("the %s came only %.2f m closer (needs 0.20 m)" % (name, meas.get("reduction_m", 0)))
            else:
                lines.append("relation '%s' does not hold for the %s" % (kind.replace("_", " "), name))
    contacts = [c for c in diagnostics["geometry"]["contacts"] if c.get("distance") is not None]
    if not diagnostics["checks"].get("penetration") and contacts:
        worst = min(contacts, key=lambda c: c["distance"])
        lines.append("the %s goes %.0f mm into the %s (limit 3 mm)" % (labels.get(worst["id_a"], worst["id_a"]), -1000 * worst["distance"], labels.get(worst["id_b"], worst["id_b"])))
    if not diagnostics["checks"].get("room_bounds"):
        lines.append("part of the scene ends up outside the room")
    settling = diagnostics["measurements"]["settling"]
    if not (diagnostics["checks"].get("settling_translation") and diagnostics["checks"].get("settling_rotation")):
        key, row = max(settling.items(), key=lambda kv: kv[1]["translation_m"] + kv[1]["rotation_deg"] / 100)
        lines.append("released for 1 s, the %s falls or slides %.0f mm and turns %.0f degrees (limits 15 mm, 3 degrees)" % (
            labels.get(key, key), 1000 * row["translation_m"], row["rotation_deg"]))
    return lines


