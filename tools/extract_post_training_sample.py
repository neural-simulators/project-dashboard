def tier_of(rate):
    return "hard" if rate < .15 else ("easy" if rate >= .5 else "medium")


def world_box(obj, position, quaternion, collision=True):
    """World AABB (x0, y0, z0, x1, y1, z1) of an object at a pose, from the collision bounds when recorded."""
    geometry = obj["geometry"]
    low = geometry.get("collision_aabb_local_min") if collision and "primitive" not in obj else None
    high = geometry.get("collision_aabb_local_max") if collision and "primitive" not in obj else None
    low, high = low or geometry["aabb_local_min"], high or geometry["aabb_local_max"]
    corners = [rotate(quaternion, [x, y, z]) for x in (low[0], high[0]) for y in (low[1], high[1]) for z in (low[2], high[2])]
    pts = [[position[i] + c[i] for i in range(3)] for c in corners]
    return [min(p[0] for p in pts), min(p[1] for p in pts), min(p[2] for p in pts), max(p[0] for p in pts), max(p[1] for p in pts), max(p[2] for p in pts)]


