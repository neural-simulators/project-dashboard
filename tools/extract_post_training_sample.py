def r4(value):
    if isinstance(value, float):
        rounded = round(value, 4)
        return 0.0 if rounded == 0 else rounded
    if isinstance(value, list):
        return [r4(v) for v in value]
    if isinstance(value, dict):
        return {k: r4(v) for k, v in value.items()}
    return value


def load(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def rotate(q, v):
    w, x, y, z = q
    vx, vy, vz = v
    # quaternion rotation of a vector, q v q*
    tx, ty, tz = 2 * (y * vz - z * vy), 2 * (z * vx - x * vz), 2 * (x * vy - y * vx)
    return [vx + w * tx + (y * tz - z * ty), vy + w * ty + (z * tx - x * tz), vz + w * tz + (x * ty - y * tx)]


def yaw_only(q):
    return abs(q[1]) < 1e-3 and abs(q[2]) < 1e-3


def yaw_deg(q):
    w, x, y, z = q
    return math.degrees(math.atan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z)))


def placed(obj, position, quaternion):
    """Footprint polygon (4 corners, world xy), bottom height and yaw of an object at a pose."""
    low, high = obj["geometry"]["aabb_local_min"], obj["geometry"]["aabb_local_max"]
    corners = [[x, y, z] for x in (low[0], high[0]) for y in (low[1], high[1]) for z in (low[2], high[2])]
    world = [[position[i] + c[i] for i in range(3)] for c in (rotate(quaternion, corner) for corner in corners)]
    bottom = min(c[2] for c in world)
    if yaw_only(quaternion):
        yaw = math.radians(yaw_deg(quaternion))
        cos, sin = math.cos(yaw), math.sin(yaw)
        footprint = [[position[0] + cos * x - sin * y, position[1] + sin * x + cos * y]
                     for x, y in ((low[0], low[1]), (high[0], low[1]), (high[0], high[1]), (low[0], high[1]))]
    else:   # not a yaw: draw the axis-aligned world footprint
        xs, ys = [c[0] for c in world], [c[1] for c in world]
        footprint = [[min(xs), min(ys)], [max(xs), min(ys)], [max(xs), max(ys)], [min(xs), max(ys)]]
    front = obj["geometry"].get("semantic_front_axis_local")
    heading = rotate(quaternion, front) if front else None
    return {"position": position, "yaw_deg": yaw_deg(quaternion), "footprint": footprint, "bottom_z": bottom,
            "heading": [heading[0], heading[1]] if heading else None}


def scene_record(manifest):
    objects = []
    for obj in manifest["objects"]:
        row = {"id": obj["id"], "label": obj["label"], "category": obj["category"], "color": obj["color"],
               "motion_type": obj["motion_type"], "quaternion_wxyz": obj["quaternion_wxyz"],
               "aabb_local_min": obj["geometry"]["aabb_local_min"], "aabb_local_max": obj["geometry"]["aabb_local_max"]}
        row.update(placed(obj, obj["position"], obj["quaternion_wxyz"]))
        row["box"] = world_box(obj, obj["position"], obj["quaternion_wxyz"])
        objects.append(row)
    patches = [p for p in manifest.get("support_patches", []) if p["id"] == "table_top"]
    if len(patches) != 1:
        raise SystemExit("expected one table_top support patch in %s" % manifest["scene_id"])
    table = next(o for o in manifest["objects"] if o["id"] == patches[0]["parent_id"])
    low, high = patches[0]["bounds_local_m"]
    table_top = {"parent_id": table["id"], "z": table["position"][2] + high[2],
                 "rect": [[table["position"][0] + low[0], table["position"][1] + low[1]], [table["position"][0] + high[0], table["position"][1] + high[1]]]}
    room = manifest["room_bounds_m"]
    return {"scene_id": manifest["scene_id"], "snapshot_hash": manifest["snapshot_hash"], "room": {"min": room["min"][:2], "max": room["max"][:2]},
            "objects": objects, "table_top": table_top, "object_count": len(objects),
            "movable_count": sum(o["motion_type"] == "dynamic" for o in manifest["objects"])}


def apply_changes(manifest, changes):
    """Precomputed poses of the objects an answer moves; the rest of the scene is unchanged."""
    objects = {o["id"]: o for o in manifest["objects"]}
    out = {}
    for change in changes:
        if change.get("id") not in objects:
            raise ValueError("unknown object id %r" % change.get("id"))
        obj = objects[change["id"]]
        position = change.get("position") if change.get("position") is not None else obj["position"]
        quaternion = change.get("quaternion_wxyz") if change.get("quaternion_wxyz") is not None else obj["quaternion_wxyz"]
        if len(position) != 3 or len(quaternion) != 4:
            raise ValueError("malformed pose for %s" % change["id"])
        norm = math.sqrt(sum(c * c for c in quaternion))
        quaternion = [c / norm for c in quaternion]
        entry = placed(obj, position, quaternion)
        entry["moved"] = change.get("position") is not None
        entry["turned"] = change.get("quaternion_wxyz") is not None
        entry["rest_bottom_z"] = placed(obj, obj["position"], obj["quaternion_wxyz"])["bottom_z"]
        entry["box"] = world_box(obj, position, quaternion)   # collision bounds, for the front view
        out[change["id"]] = entry
    return out


def parse_answer(text):
    """The model's JSON answer, or None when it is not a JSON object (the verifier then scores format 0)."""
    try:
        value = json.loads(text)
    except ValueError:
        return None
    return value if isinstance(value, dict) else None


