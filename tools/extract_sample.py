#!/usr/bin/env python3
"""Extract the sample trajectory that drives the page's animations.

Reads the sample task's public scene manifest and task JSON from the simagent
repository, finds the PhysX witness rollout through the flight qualification
summary, and writes ``static/data/world_model.js`` (the world-model proposal's
data file, one per proposal slug) defining ``window.WM_SAMPLE``.  The data is
embedded as a script so that the page works from ``file://`` without any
fetch.  Standard library only.

    python3 tools/extract_sample.py [--simagent-root PATH] [--output PATH]

The simagent root defaults to ``$SIMAGENT_ROOT``, else the parent directory of
this repository (the dashboard lives at ``<simagent>/project-dashboard``).
Every float is rounded to 4 decimals.  The script fails instead of guessing
when an input is missing or has an unexpected shape.
"""
import argparse
import json
import os
import sys
from pathlib import Path

TASK_ID = "b2_room_01_ball_over_barrier_hit_blue"
BUNDLE = Path("observations/benchmark_v2") / TASK_ID
QUALIFICATION = Path("runs/benchmark_v2/isaac_qualification_flight_v4")
BALLS = ("o024", "o025")
BARRIER = "o027"
EXPECTED_FRAMES = 61
HEADER = (
    "// Generated by tools/extract_sample.py from the simagent repository; do not edit by hand.\n"
    "// Sample task {task}: public scene manifest + PhysX witness rollout ({qual}).\n"
    "// Floats rounded to 4 decimals. Units: metres, seconds, m/s; right-handed Z-up.\n"
)


def r4(value):
    if isinstance(value, float):
        rounded = round(value, 4)
        return 0.0 if rounded == 0 else rounded
    if isinstance(value, list):
        return [r4(v) for v in value]
    if isinstance(value, dict):
        return {k: r4(v) for k, v in value.items()}
    return value


def load(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def find_rollout(root, summary):
    rows = [row for row in summary["cases"] if row.get("task_id") == TASK_ID]
    if len(rows) != 1:
        raise SystemExit("expected exactly one summary row for %s, found %d" % (TASK_ID, len(rows)))
    row = rows[0]
    if not row.get("qualified"):
        raise SystemExit("summary row for %s is not qualified (status %s)" % (TASK_ID, row.get("status")))
    candidates = [
        Path(row["output"]) / "reference_rollout.json",
        root / QUALIFICATION / "cases" / TASK_ID / "reference_rollout.json",
    ]
    for candidate in candidates:
        if candidate.is_file():
            return candidate, row
    raise SystemExit("reference_rollout.json not found; tried %s" % ", ".join(str(c) for c in candidates))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    repo = Path(__file__).resolve().parents[1]
    default_root = os.environ.get("SIMAGENT_ROOT") or str(repo.parent)
    parser.add_argument("--simagent-root", default=default_root, help="simagent checkout (default: %(default)s)")
    parser.add_argument("--output", default=str(repo / "static" / "data" / "world_model.js"))
    args = parser.parse_args(argv)
    root = Path(args.simagent_root).resolve()

    manifest = load(root / BUNDLE / "scene_manifest.json")
    task = load(root / BUNDLE / "task.json")
    summary = load(root / QUALIFICATION / "summary.json")
    rollout_path, row = find_rollout(root, summary)
    rollout = load(rollout_path)

    if rollout.get("task_id") != TASK_ID or rollout.get("snapshot_hash") != manifest["snapshot_hash"]:
        raise SystemExit("rollout does not match the manifest (task id or snapshot hash differ)")
    states = rollout["states"]
    if len(states) != EXPECTED_FRAMES:
        raise SystemExit("expected %d sampled states, found %d" % (EXPECTED_FRAMES, len(states)))
    launch = rollout["initial_changes"]
    if len(launch) != 1 or launch[0]["id"] != BALLS[0]:
        raise SystemExit("expected one launch of %s, found %r" % (BALLS[0], launch))

    objects = {obj["id"]: obj for obj in manifest["objects"]}
    for needed in BALLS + (BARRIER,):
        if needed not in objects:
            raise SystemExit("object %s missing from the manifest" % needed)

    time_s = [state["time_s"] for state in states]
    balls = {}
    for ball_id in BALLS:
        obj = objects[ball_id]
        if obj["primitive"]["kind"] != "sphere":
            raise SystemExit("%s is not a sphere" % ball_id)
        positions, velocities, quaternions, spins = [], [], [], []
        for state in states:
            match = [o for o in state["objects"] if o["id"] == ball_id]
            if len(match) != 1:
                raise SystemExit("state at t=%s has %d entries for %s" % (state["time_s"], len(match), ball_id))
            positions.append(match[0]["position"])
            velocities.append(match[0]["linear_velocity"])
            quaternions.append(match[0]["quaternion_wxyz"])
            spins.append(match[0]["angular_velocity"])
        inertia = obj.get("inertia_local_kg_m2")
        balls[ball_id] = {
            "label": obj["label"],
            "color": obj["color"],
            "radius_m": obj["primitive"]["radius"],
            "mass_kg": obj["mass_kg"],
            "friction": obj["friction"],
            "restitution": obj["restitution"],
            "linear_damping": obj.get("linear_damping", 0.0),
            "angular_damping": obj.get("angular_damping", 0.0),
            "inertia_diag_kg_m2": [inertia[i][i] for i in range(3)] if inertia else None,
            "start_position": obj["position"],
            "position": positions,
            "linear_velocity": velocities,
            "quaternion_wxyz": quaternions,
            "angular_velocity": spins,
        }

    barrier = objects[BARRIER]
    if barrier["primitive"]["kind"] != "box":
        raise SystemExit("%s is not a box" % BARRIER)
    contacts = [
        {"time_s": e["time_s"], "id_a": e["id_a"], "id_b": e["id_b"]}
        for e in rollout["contact_events"]
        if e["id_a"] in BALLS or e["id_b"] in BALLS
    ]

    sample = {
        "task_id": TASK_ID,
        "scene_id": manifest["scene_id"],
        "instruction": task["instruction"],
        "fps": task["fps"],
        "horizon_s": task["horizon_s"],
        "launch": launch[0],
        "time_s": time_s,
        "objects": balls,
        "barrier": {
            "id": BARRIER,
            "label": barrier["label"],
            "position": barrier["position"],
            "size": barrier["primitive"]["size"],
        },
        "red_ball_radius_m": objects[BALLS[0]]["primitive"]["radius"],
        "contact_events": contacts,
        "object_ids": [obj["id"] for obj in manifest["objects"]],
        "movable_object_ids": rollout["all_movable_object_ids"],
        "gravity": manifest["physics"]["gravity"],
        "physics_timestep_s": manifest["physics"]["timestep_s"],
        "source": {
            "manifest": str(BUNDLE / "scene_manifest.json"),
            "task": str(BUNDLE / "task.json"),
            "rollout": str(rollout_path.relative_to(root)) if rollout_path.is_relative_to(root) else str(rollout_path),
            "qualification_status": row["status"],
            "snapshot_hash": manifest["snapshot_hash"],
            "generator": "tools/extract_sample.py",
        },
    }
    body = json.dumps(r4(sample), indent=1, sort_keys=True, allow_nan=False)
    text = HEADER.format(task=TASK_ID, qual=str(QUALIFICATION)) + "window.WM_SAMPLE = " + body + ";\n"
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print("wrote %s (%d bytes, %d frames, %d contact events, %d objects, %d movable)" % (
        out, len(text.encode("utf-8")), len(time_s), len(contacts), len(sample["object_ids"]),
        len(sample["movable_object_ids"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
