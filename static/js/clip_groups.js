/* Clip galleries on the results pages (Scaled results, Improved Results V1, V2, ...).

   A comparison gallery (the physics engine next to every learned simulator, one clip per scene) is folded into groups by
   kind of scene, closed by default, so the page opens short. A clip plays while the pointer is over it, or over its open
   group, and pauses when the pointer leaves or the clip scrolls out of view; on touch screens the clips keep their play
   button. Comparison galleries are recognised by the column count set on the gallery element itself
   (style="grid-template-columns: ...") and need at least eight clips of three kinds or more. A gallery arranged by theme
   (no column count of its own, under a heading paragraph p.dhead) is folded under its heading instead; the heading's id
   moves to the fold, and the page's own script opens a <details> that a link targets. Clips that autoplay are never
   touched.

   The results pages are generated by builders that copy the <head> of end-to-end.html, so this script reaches every
   regenerated page through that head. Styles: project.css, "Clip groups". */
(function () {
  'use strict';
  var FAMILIES = [
    ['Drops, throws and ramps', /^(drop|throw|ramp|place|avoid|spin|rebound|toss)\b/],
    ['Pushes and collisions', /^(slide|hit|chain|push|composite|collide)\b/],
    ['Toppling, dominoes and stacks', /^(topple|domino|jenga|stack)/],
    ['Pendulums and springs', /^(pendulum|spring)\b/],
    ['Soft bodies, cloth and ropes', /^(soft|rope|cloth)/],
    ['Complete rooms and outside datasets', /^(complete|sparse|physion|movi|same action|room)/]
  ];
  var MIN_CLIPS = 8, MIN_KINDS = 3;
  var canHover = window.matchMedia ? window.matchMedia('(hover: hover) and (pointer: fine)').matches : true;

  // "training scene · drop · easy · drop ball at ..." -> "drop"; "soft body: trampoline · ..." -> "soft body: trampoline"
  function rawKind(card) {
    var lab = card.querySelector('.lab');
    if (!lab) { return ''; }
    var parts = lab.textContent.split('·').map(function (s) { return s.trim(); });
    if (parts[0].toLowerCase() === 'training scene') { parts.shift(); }
    return parts[0] || '';
  }

  // Short name for the group's summary: "complete scene: 58 objects" -> "complete scene", "soft body: jelly cube" -> "jelly cube"
  function shortKind(raw) {
    var k = raw.replace(/\s*\([^)]*\)/g, '').split(',')[0], c = k.indexOf(':');
    if (c >= 0) { k = /^soft body/i.test(k) ? k.slice(c + 1) : k.slice(0, c); }
    return k.trim();
  }

  function regroup(gallery) {
    if (!gallery.style.gridTemplateColumns || !gallery.parentNode) { return; }
    var cards = [].filter.call(gallery.children, function (c) { return c.querySelector('video'); });
    if (cards.length < MIN_CLIPS || cards.length !== gallery.children.length) { return; }
    var groups = [], used = 0;
    for (var n = 0; n <= FAMILIES.length; n++) { groups.push({ cards: [], kinds: [] }); }
    cards.forEach(function (card) {
      var raw = rawKind(card), key = raw.toLowerCase(), f = FAMILIES.length;
      for (var i = 0; i < FAMILIES.length; i++) { if (FAMILIES[i][1].test(key)) { f = i; break; } }
      if (!groups[f].cards.length) { used++; }
      groups[f].cards.push(card);
      var s = shortKind(raw);
      if (s && groups[f].kinds.indexOf(s) < 0) { groups[f].kinds.push(s); }
    });
    if (used < MIN_KINDS) { return; }
    var list = document.createElement('div'), hint = document.createElement('p');
    list.className = 'clipfam-list';
    hint.className = 'clipfam-hint';
    hint.textContent = canHover ? 'Grouped by kind of scene. Open a group; its clips play while the pointer is over them.'
                                : 'Grouped by kind of scene. Open a group and tap a clip to play it.';
    list.appendChild(hint);
    groups.forEach(function (g, f) {
      if (!g.cards.length) { return; }
      var d = document.createElement('details'), s = document.createElement('summary'), inner = gallery.cloneNode(false);
      var name = document.createElement('span'), count = document.createElement('span'), kinds = document.createElement('span');
      d.className = 'clipfam';
      name.className = 'clipfam-name';
      name.textContent = f < FAMILIES.length ? FAMILIES[f][0] : 'Other scenes';
      count.className = 'clipfam-count';
      count.textContent = g.cards.length + (g.cards.length === 1 ? ' scene' : ' scenes');
      kinds.className = 'clipfam-kinds';
      kinds.textContent = g.kinds.join(', ');
      s.appendChild(name); s.appendChild(count); s.appendChild(kinds);
      inner.removeAttribute('id');
      g.cards.forEach(function (c) { inner.appendChild(c); });
      d.appendChild(s); d.appendChild(inner);
      list.appendChild(d);
    });
    gallery.parentNode.replaceChild(list, gallery);
  }

  function hintFor(parent, text) {
    var hint = document.createElement('p');
    hint.className = 'clipfam-hint';
    hint.textContent = text;
    return hint;
  }

  function foldTheme(gallery) {
    if (gallery.style.gridTemplateColumns || !gallery.parentNode) { return; }
    var clips = [].filter.call(gallery.children, function (c) { return c.querySelector('video'); }).length;
    if (clips < 3) { return; }
    var note = gallery.previousElementSibling, head = note;
    if (note && note.matches('p.wm-note')) { head = note.previousElementSibling; } else { note = null; }
    if (!head || !head.matches('p.dhead')) { return; }
    var d = document.createElement('details'), s = document.createElement('summary');
    var name = document.createElement('span'), count = document.createElement('span'), parent = head.parentNode;
    d.className = 'clipfam clipfam-theme';
    if (head.id) { d.id = head.id; }
    name.className = 'clipfam-name';
    name.textContent = head.textContent;
    count.className = 'clipfam-count';
    count.textContent = clips + ' clips';
    s.appendChild(name); s.appendChild(count); d.appendChild(s);
    if (!parent.querySelector(':scope > .clipfam-theme')) {
      parent.insertBefore(hintFor(parent, canHover ? 'Each group opens on a click; its clips play while the pointer is over them.'
                                                   : 'Each group opens on a tap; tap a clip to play it.'), head);
    }
    parent.insertBefore(d, head);
    parent.removeChild(head);
    if (note) { d.appendChild(note); }
    d.appendChild(gallery);
  }

  function start(v) { var p = v.play(); if (p && p.catch) { p.catch(function () {}); } }
  function stop(v) { if (!v.paused) { v.pause(); } }

  // Clips that leave the screen stop; a clip that enters it plays if the pointer is over its group.
  var seen = typeof IntersectionObserver === 'function' ? new IntersectionObserver(function (entries) {
    entries.forEach(function (e) {
      var v = e.target;
      v.clipInView = e.isIntersecting;
      if (!e.isIntersecting) { stop(v); } else if (v.clipGroup && v.clipGroup.clipHovered) { start(v); }
    });
  }, { threshold: 0.25 }) : null;

  function setupGroup(d) {
    var clips = function () { return [].slice.call(d.querySelectorAll('video')); };
    var on = function () {
      d.clipHovered = true;
      clips().forEach(function (v) { if (v.clipInView !== false) { start(v); } });
    };
    var off = function () { d.clipHovered = false; clips().forEach(stop); };
    d.addEventListener('pointerenter', function (e) { if (e.pointerType !== 'touch' && d.open) { on(); } });
    d.addEventListener('pointerleave', function (e) { if (e.pointerType !== 'touch') { off(); } });
    d.addEventListener('toggle', function () {
      if (!d.open) { off(); } else if (canHover && d.matches(':hover')) { on(); }
    });
  }

  function setupClip(v) {
    if (v.autoplay || v.hasAttribute('autoplay')) { return; }
    v.muted = true;
    v.clipGroup = v.closest('details.clipfam');
    if (seen) { seen.observe(v); }
    var card = v.closest('.card') || v;
    card.addEventListener('pointerenter', function (e) { if (e.pointerType !== 'touch') { start(v); } });
    card.addEventListener('pointerleave', function (e) {
      if (e.pointerType !== 'touch' && !(v.clipGroup && v.clipGroup.clipHovered)) { stop(v); }
    });
    v.addEventListener('focus', function () { start(v); });
    v.addEventListener('blur', function () { if (!(v.clipGroup && v.clipGroup.clipHovered)) { stop(v); } });
  }

  function init() {
    [].forEach.call(document.querySelectorAll('.gallery'), regroup);
    [].forEach.call(document.querySelectorAll('.gallery'), foldTheme);
    if (canHover) { [].forEach.call(document.querySelectorAll('details.clipfam'), setupGroup); }
    [].forEach.call(document.querySelectorAll('.gallery video'), setupClip);
  }
  if (document.readyState === 'loading') { document.addEventListener('DOMContentLoaded', init); } else { init(); }
})();
