  function text(ctx, s, x, y, o) {
    o = o || {};
    ctx.font = (o.bold ? '600 ' : '') + (o.size || 15) + 'px ' + FONT;
    ctx.textAlign = o.align || 'left'; ctx.textBaseline = o.base || 'middle';
    if (o.halo !== false) { ctx.lineJoin = 'round'; ctx.lineWidth = 4; ctx.strokeStyle = 'rgba(255,255,255,0.92)'; ctx.strokeText(s, x, y); }
    ctx.fillStyle = o.color || C.text; ctx.fillText(s, x, y);
    return ctx.measureText(s).width;
  }
