  function fillExperiment() {
    var table = document.getElementById('pt-experiment-table');
    if (!table || !D.experiment) { return; }
    var g = D.experiment.groups, cols = [['static', 'all', 'Static edits'], ['launch', 'easy', 'Launches, easy'], ['launch', 'medium', 'Launches, medium'], ['launch', 'hard', 'Launches, hard']];
    function cell(split, c, key) { var b = g[split + '|' + c[0] + '|' + c[1]]; return b ? b[key] : 0; }
    var html = '<thead><tr><th></th>' + cols.map(function (c) { return '<th>' + c[2] + '</th>'; }).join('') + '</tr></thead><tbody>';
    html += '<tr><td>Training tasks</td>' + cols.map(function (c) { return '<td>' + cell('train', c, 'tasks') + '</td>'; }).join('') + '</tr>';
    html += '<tr><td>Held-out test tasks</td>' + cols.map(function (c) { return '<td>' + cell('test', c, 'tasks') + '</td>'; }).join('') + '</tr>';
    html += '<tr><td>Test tasks passed by Qwen3-VL-30B thinking</td>' + cols.map(function (c) { return '<td>' + cell('test', c, 'qwen30t') + '</td>'; }).join('') + '</tr>';
    html += '<tr><td>Test tasks passed by GPT-5.4</td>' + cols.map(function (c) { return '<td>' + cell('test', c, 'gpt54') + '</td>'; }).join('') + '</tr>';
    html += '<tr><td>Test tasks passed by the untrained 7B</td>' + cols.map(function () { return '<td class="pending">in progress</td>'; }).join('') + '</tr></tbody>';
    table.innerHTML = html;
  }

