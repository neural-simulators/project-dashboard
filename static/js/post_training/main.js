  function bbox(points) {
    var b = { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity };
    for (var i = 0; i < points.length; i++) {
      b.x0 = Math.min(b.x0, points[i][0]); b.y0 = Math.min(b.y0, points[i][1]);
      b.x1 = Math.max(b.x1, points[i][0]); b.y1 = Math.max(b.y1, points[i][1]);
    }
    return b;
  }
  function grow(b, margin, minW, minH) {
    var out = { x0: b.x0 - margin, y0: b.y0 - margin, x1: b.x1 + margin, y1: b.y1 + margin };
    var w = out.x1 - out.x0, h = out.y1 - out.y0;
    if (w < minW) { out.x0 -= (minW - w) / 2; out.x1 += (minW - w) / 2; }
    if (h < minH) { out.y0 -= (minH - h) / 2; out.y1 += (minH - h) / 2; }
    return out;
  }
  function intersect(a, b) {
    var r = { x0: Math.max(a.x0, b.x0), y0: Math.max(a.y0, b.y0), x1: Math.min(a.x1, b.x1), y1: Math.min(a.y1, b.y1) };
    return (r.x1 > r.x0 && r.y1 > r.y0) ? r : null;
  }
  function lerpPoints(a, b, t) { var out = []; for (var i = 0; i < a.length; i++) { out.push([lerp(a[i][0], b[i][0], t), lerp(a[i][1], b[i][1], t)]); } return out; }
