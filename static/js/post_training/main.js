  /* ------------------------------------------------------------------ small helpers */
  function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').split('\u0022').join('&quot;'); }
  function clamp01(x) { return x < 0 ? 0 : (x > 1 ? 1 : x); }
  function ease(u) { u = clamp01(u); return u < 0.5 ? 2 * u * u : 1 - Math.pow(-2 * u + 2, 2) / 2; }
  function lerp(a, b, t) { return a + (b - a) * t; }
  function fmt(x, d) { return Number(x).toFixed(d); }
  function signed(x, d) { return (x >= 0 ? '+' : '−') + fmt(Math.abs(x), d); }
  function cap(s) { return s.charAt(0).toUpperCase() + s.slice(1); }
  function bbox(points) {
    var b = { x0: Infinity, y0: Infinity, x1: -Infinity, y1: -Infinity };
    for (var i = 0; i < points.length; i++) {
      b.x0 = Math.min(b.x0, points[i][0]); b.y0 = Math.min(b.y0, points[i][1]);
      b.x1 = Math.max(b.x1, points[i][0]); b.y1 = Math.max(b.y1, points[i][1]);
    }
    return b;
  }
  function grow(b, margin, minW, minH) {
    var out = { x0: b.x0 - margin, y0: b.y0 - margin, x1: b.x1 + margin, y1: b.y1 + margin };
    var w = out.x1 - out.x0, h = out.y1 - out.y0;
    if (w < minW) { out.x0 -= (minW - w) / 2; out.x1 += (minW - w) / 2; }
    if (h < minH) { out.y0 -= (minH - h) / 2; out.y1 += (minH - h) / 2; }
    return out;
  }
  function intersect(a, b) {
    var r = { x0: Math.max(a.x0, b.x0), y0: Math.max(a.y0, b.y0), x1: Math.min(a.x1, b.x1), y1: Math.min(a.y1, b.y1) };
    return (r.x1 > r.x0 && r.y1 > r.y0) ? r : null;
  }
  function lerpPoints(a, b, t) { var out = []; for (var i = 0; i < a.length; i++) { out.push([lerp(a[i][0], b[i][0], t), lerp(a[i][1], b[i][1], t)]); } return out; }
  function findObj(scene, id) { for (var i = 0; i < scene.objects.length; i++) { if (scene.objects[i].id === id) { return scene.objects[i]; } } return null; }
  function labelOf(scene, id) { var o = findObj(scene, id); return o ? o.label : id; }
  function cm(m) { return Math.abs(m) >= 0.01 ? fmt(Math.abs(m) * 100, 0) + ' cm' : fmt(Math.abs(m) * 1000, 0) + ' mm'; }
  function swatch(color) { return '<span class="pt-swatch" style="background:' + color + '"></span>'; }
  function badge(pass, words) { return '<span class="pt-badge ' + (pass ? 'pass' : 'fail') + '">' + esc(words || (pass ? 'passes' : 'fails')) + '</span>'; }
  function tierBadge(tier) { return '<span class="pt-badge ' + tier + '">' + tier + '</span>'; }
  function whoName(who) { return (WHO[who] || { name: who }).name; }
  function whoShort(who, W) { return W < NARROW ? (WHO[who] || { short: who }).short : whoName(who); }
  function whoColor(who) { return (WHO[who] || { color: C.slate }).color; }
  function roomName(taskId) { var m = /room_(\d+)/.exec(taskId); return m ? 'Room ' + parseInt(m[1], 10) : taskId; }

  /* ------------------------------------------------------------------ canvas and text */
  function fit(canvas, aspect, minH, maxH) {
    var W = canvas.clientWidth || parseInt(canvas.getAttribute('width'), 10) || 560;
    var H = Math.round(Math.max(minH, Math.min(maxH, W * aspect)));
    var f = WM.fitCanvas(canvas, H);
    f.ctx.clearRect(0, 0, f.W, f.H);
    f.ctx.fillStyle = '#fff'; f.ctx.fillRect(0, 0, f.W, f.H);
    return f;
  }
  function text(ctx, s, x, y, o) {
    o = o || {};
    ctx.font = (o.bold ? '600 ' : '') + (o.size || 15) + 'px ' + FONT;
    ctx.textAlign = o.align || 'left'; ctx.textBaseline = o.base || 'middle';
    if (o.halo !== false) { ctx.lineJoin = 'round'; ctx.lineWidth = 4; ctx.strokeStyle = 'rgba(255,255,255,0.92)'; ctx.strokeText(s, x, y); }
    ctx.fillStyle = o.color || C.text; ctx.fillText(s, x, y);
    return ctx.measureText(s).width;
  }
  function areaTag(ctx, rect, s, short) { text(ctx, rect.w < NARROW && short ? short : s, rect.x + 8, rect.y + 12, { size: 13, color: C.muted }); }
  function makeView(box, rect, pad, bottom) {
    var s = Math.min((rect.w - 2 * pad) / (box.x1 - box.x0), (rect.h - 2 * pad) / (box.y1 - box.y0));
    var ox = rect.x + (rect.w - s * (box.x1 - box.x0)) / 2, oy = bottom ? rect.y + rect.h - pad - s * (box.y1 - box.y0) : rect.y + (rect.h - s * (box.y1 - box.y0)) / 2;
    return { s: s, box: box, rect: rect, X: function (x) { return ox + (x - box.x0) * s; }, Y: function (y) { return oy + (box.y1 - y) * s; } };
  }
  function clip(ctx, rect) { ctx.save(); ctx.beginPath(); ctx.rect(rect.x, rect.y, rect.w, rect.h); ctx.clip(); }
  function poly(ctx, v, points) {
    ctx.beginPath();
    for (var i = 0; i < points.length; i++) { if (i === 0) { ctx.moveTo(v.X(points[i][0]), v.Y(points[i][1])); } else { ctx.lineTo(v.X(points[i][0]), v.Y(points[i][1])); } }
    ctx.closePath();
  }
  function arrow(ctx, x0, y0, x1, y1, color, width) {
    var a = Math.atan2(y1 - y0, x1 - x0), L = Math.hypot(x1 - x0, y1 - y0);
    if (L < 2) { return; }
    ctx.strokeStyle = color; ctx.fillStyle = color; ctx.lineWidth = width || 2;
    ctx.beginPath(); ctx.moveTo(x0, y0); ctx.lineTo(x1 - 8 * Math.cos(a), y1 - 8 * Math.sin(a)); ctx.stroke();
    ctx.beginPath(); ctx.moveTo(x1, y1);
    ctx.lineTo(x1 - 11 * Math.cos(a - 0.45), y1 - 11 * Math.sin(a - 0.45));
    ctx.lineTo(x1 - 11 * Math.cos(a + 0.45), y1 - 11 * Math.sin(a + 0.45));
    ctx.closePath(); ctx.fill();
  }
  function hatch(ctx, r, color) {
    ctx.save(); ctx.beginPath(); ctx.rect(r.x, r.y, r.w, r.h); ctx.clip();
    ctx.strokeStyle = color; ctx.lineWidth = 1.6;
    for (var k = -r.h; k < r.w + r.h; k += 7) { ctx.beginPath(); ctx.moveTo(r.x + k, r.y); ctx.lineTo(r.x + k + r.h, r.y + r.h); ctx.stroke(); }
    ctx.restore();
    ctx.strokeStyle = color; ctx.lineWidth = 2; ctx.strokeRect(r.x, r.y, r.w, r.h);
  }
  /* greedy label placement: labels never print on top of each other and never leave the drawing area */
  function Labels(rect) { this.boxes = []; this.rect = rect || null; }
  Labels.prototype.put = function (ctx, s, x, y, o) {
    o = o || {}; ctx.font = (o.bold ? '600 ' : '') + (o.size || 15) + 'px ' + FONT;
    var w = ctx.measureText(s).width, h = (o.size || 15) + 4, align = o.align || 'center', R = this.rect;
    if (R && o.flipX !== undefined && align === 'left' && x + w > R.x + R.w - 4) { x = o.flipX; align = 'right'; }
    var x0 = align === 'center' ? x - w / 2 : (align === 'left' ? x : x - w);
    if (R) { var shift = Math.max(R.x + 4 - x0, 0) + Math.min(R.x + R.w - 4 - (x0 + w), 0); x0 += shift; x += shift; }
    for (var attempt = 0; attempt < 6; attempt++) {
      var yy = y + attempt * (o.step || h) * (o.up ? -1 : 1);
      if (R) { yy = Math.max(R.y + h / 2 + 2, Math.min(R.y + R.h - h / 2 - 2, yy)); }
      var r = { x0: x0, y0: yy - h / 2, x1: x0 + w, y1: yy + h / 2 }, clash = false;
      for (var i = 0; i < this.boxes.length; i++) { if (intersect(r, this.boxes[i])) { clash = true; break; } }
      if (!clash || attempt === 5) { this.boxes.push(r); text(ctx, s, x, yy, { size: o.size, bold: o.bold, color: o.color, align: align }); return; }
    }
  };

  /* ------------------------------------------------------------------ the step engine shared by the three widgets */
  function Widget(rootId, scenes, opts) {
    var root = document.getElementById(rootId);
    if (!root) { return; }
    opts = opts || {};
    var canvas = root.querySelector('canvas'), side = root.querySelector('.pt-side');
    var picker = root.querySelector('.pt-picker'), steps = root.querySelector('.pt-steps');
    var toggle = root.querySelector('[data-action="toggle"]'), next = root.querySelector('[data-action="next"]');
    var st = { s: 0, p: 0, t: 0 }, shown = null, control = null, pickButtons = [];
    function playing() { return !toggle || toggle.getAttribute('aria-pressed') === 'true'; }
    function phase() { return scenes[st.s].phases[st.p]; }
    function go(s, p) { st.s = s; st.p = p; st.t = playing() ? 0 : scenes[s].phases[p].seconds; shown = null; render(); }
    if (picker) {
      if (scenes.length < 2) { picker.hidden = true; }
      scenes.forEach(function (scene, i) {
        var b = document.createElement('button');
        b.type = 'button'; b.className = 'button is-small'; b.textContent = scene.label;
        b.addEventListener('click', function () { go(i, 0); });
        picker.appendChild(b); pickButtons.push(b);
      });
    }
    function chrome() {
      pickButtons.forEach(function (b, i) { b.classList.toggle('is-selected', i === st.s); b.setAttribute('aria-pressed', i === st.s ? 'true' : 'false'); });
      if (!steps) { return; }
      steps.innerHTML = '';
      scenes[st.s].phases.forEach(function (ph, i) {
        var b = document.createElement('button');
        b.type = 'button'; b.textContent = (i + 1) + '. ' + ph.step;
        if (i === st.p) { b.className = 'is-current'; }
        b.addEventListener('click', function () { go(st.s, i); });
        steps.appendChild(b);
      });
    }
    function reveal(ph, u) {
      if (!ph.reveal) { return 0; }
      var a = ph.revealFrom || 0.3, b = ph.revealTo || 0.9;
      return Math.min(ph.reveal, Math.floor(clamp01((u - a) / (b - a)) * (ph.reveal + 1)));
    }
    function render() {
      var ph = phase(), u = clamp01(st.t / ph.seconds), n = reveal(ph, u);
      var f = fit(canvas, opts.aspect || 0.78, opts.minH || 320, opts.maxH || 460);
      ph.draw(f.ctx, f.W, f.H, u, n);
      var key = st.s + ':' + st.p + ':' + n;
      if (key !== shown) { side.innerHTML = ph.side(n); chrome(); shown = key; }
    }
    function advance(dt) {
      st.t += dt;
      if (st.t >= phase().seconds + HOLD) {
        st.t = 0; st.p += 1;
        if (st.p >= scenes[st.s].phases.length) { st.p = 0; st.s = (st.s + 1) % scenes.length; }
      }
    }
    if (next) {
      next.addEventListener('click', function () {
        var p = st.p + 1, s = st.s;
        if (p >= scenes[s].phases.length) { p = 0; s = (s + 1) % scenes.length; }
        go(s, p);
      });
    }
    control = WM.runner({ root: root, button: toggle, advance: advance, render: render,
                          representative: function () { st.s = 0; st.p = opts.representative || 0; st.t = scenes[0].phases[st.p].seconds; } });
    return control;
  }

