  function dpoStaticScene() {
    var P = D.dpo_pair, scene = D.scenes[P.scene_id], label = function (id) { return labelOf(scene, id); };
    var focus = ['o006', 'o007', 'o009', 'o010', 'o011'];
    var chosen = { poses: P.chosen.poses, color: C.blue, ghost: false, labelHere: false }, rejected = { poses: P.rejected.poses, color: C.red, ghost: false, dash: [5, 3], labelHere: false };
    var sunk = scene.table_top.z - P.rejected.poses.o011.bottom_z;
    function pair(ctx, W, H) {
      var A = staticAreas(W, H);
      drawPlan(ctx, A.plan, scene, focus, [rejected, chosen], {});
      drawFront(ctx, A.front, scene, ['o011'], ['o009', 'o010'], 'o006', [rejected, chosen]);
      legend(ctx, 12, A.plan.y + 34, [{ color: C.blue, label: 'better answer' }, { color: C.red, label: 'worse answer' }]);
    }
    return { label: 'Static edit: room 8 pair', phases: [
      { step: 'Two answers', seconds: 7, draw: function (ctx, W, H) { pair(ctx, W, H); },
        side: function () {
          return '<h4>Two answers from the same model</h4><p class="pt-instr">“' + esc(P.instruction) + '”</p>' +
            '<p>Two of the sixteen answers the untrained 7B model wrote for this prompt. The better one (blue) puts the ' + esc(label('o011')) + ' flat between the cups and turns the chair toward the table: every check holds. The worse one (red) puts the book ' + cm(sunk) + ' into the table top and tips the chair onto its side.</p>';
        } },
      { step: 'Scores', seconds: 6, draw: function (ctx, W, H) { pair(ctx, W, H); },
        side: function () {
          return '<h4>Their rewards</h4>' + rewardTable([{ who: 'qwen7', pass: P.chosen.pass, reward: P.chosen.reward }, { who: 'qwen7', pass: P.rejected.pass, reward: P.rejected.reward }]).replace(/Qwen2\.5-7B, untrained/, 'better answer').replace(/Qwen2\.5-7B, untrained/, 'worse answer') +
            '<p>A pair is kept for DPO when the two rewards differ by at least 0.25; this one differs by ' + fmt(P.reward_gap, 2) + '. In the first sampling run the 160 answers to ten prompts gave 16 such pairs.</p>';
        } },
      { step: 'The update', seconds: 8, draw: function (ctx, W, H, u) { lossPanel(ctx, W, H, u, D.constants.dpo.beta); },
        side: function () {
          return '<h4>The DPO update</h4><p>DPO raises the probability of the better answer and lowers that of the worse one, both measured against the untrained model, until the model clearly prefers the better one. Once the margin is large the loss flattens and the pair stops mattering.</p>' +
            '<p>No simulator and no sampling are needed during training, which makes DPO the cheapest baseline. Its limit: it can only reorder answers the model already writes.</p>';
        } }
    ] };
  }
  function dpoLaunchScene() {
    var ex = D.examples.filter(function (e) { return e.task_id === D.launch_group.task_id; })[0];
    var good = ex.answers.filter(function (a) { return a.who === 'qwen30t'; })[0], bad = ex.answers.filter(function (a) { return a.who === 'qwen30'; })[0];
    function pair(ctx, W, H) {
      drawSide(ctx, { x: 0, y: 0, w: W, h: H }, ex, [{ answer: bad, color: C.red, frame: 60, end: true }, { answer: good, color: C.blue, frame: 60, end: true }, { answer: good, color: C.blue, frame: 0, balls: true, alpha: 0 }]);
      legend(ctx, 14, 40, W < NARROW ? [{ color: C.blue, label: 'better launch' }, { color: C.red, label: 'worse launch' }] : [{ color: C.blue, label: 'better: ' + launchText(good.launch) }, { color: C.red, label: 'worse: ' + launchText(bad.launch) }]);
    }
    return { label: 'Launch: room 2 pair', phases: [
      { step: 'Two launches', seconds: 7, draw: function (ctx, W, H) { pair(ctx, W, H); },
        side: function () {
          return '<h4>A better and a worse launch</h4><p class="pt-instr">“' + esc(ex.instruction) + '”</p>' +
            '<p>Both launches clear the barrier. The better one (blue) lands in the box and stays; the worse one (red) is too flat and stops ' + esc(bad.why.join(' ').replace(/^the red ball stops at x = [0-9.]+ m, /, '')) + '.</p>' +
            '<p class="pt-small">These two are real answers by the 30B model with and without thinking. In training, both sides of a pair come from the model being trained.</p>';
        } },
      { step: 'Scores', seconds: 6, draw: function (ctx, W, H) { pair(ctx, W, H); },
        side: function () {
          return '<h4>Their rewards</h4>' + rewardTable([good, bad]) + '<p>The worse launch still meets two of the three checks, so the gap is ' + fmt(good.reward - bad.reward, 2) + ', enough for a pair. Both numbers come from simulations.</p>';
        } },
      { step: 'The update', seconds: 8, draw: function (ctx, W, H, u) { lossPanel(ctx, W, H, u, D.constants.dpo.beta); },
        side: function () {
          return '<h4>Same update for launches</h4><p>The pair’s text is the launch JSON. DPO shifts the model toward the steeper launch and away from the flat one. For launches the expensive part is labelling the pairs: every sampled launch is simulated once before training starts.</p>';
        } }
    ] };
  }

