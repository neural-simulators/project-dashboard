  /* ------------------------------------------------------------------ the planner widget */
  function goalWords(ex, goal) {
    var g = goal.goal, count = g.metric === 'count_toppled';
    if (count) { return g.op === '>=' && g.value === ex.topple_objects.length ? 'topple all ' + g.value + ' pins' : (g.op === '<=' ? 'topple at most ' : 'topple at least ') + g.value + ' of the ' + ex.topple_objects.length + ' pins'; }
    return 'move the block ' + (g.op === '<=' ? 'at most ' : 'at least ') + fmt(g.value, 2) + ' m';
  }
  function programWords(ex) {
    var p = ex.program, f = Math.hypot.apply(null, p.force_N);
    return 'the pusher presses with ' + fmt(f, 1) + ' N from ' + fmt(p.start_s, 2) + ' to ' + fmt(p.stop_s, 2) + ' s';
  }
