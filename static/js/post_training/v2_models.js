          for (var i = 0; i <= Math.min(f, path.length - 1); i++) { if (i === 0) { ctx.moveTo(v.X(path[i][0]), v.Y(path[i][1])); } else { ctx.lineTo(v.X(path[i][0]), v.Y(path[i][1])); } }
