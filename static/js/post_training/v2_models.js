    for (var gx = Math.ceil(win.x0 * 2) / 2; gx <= win.x1; gx += 0.5) { ctx.beginPath(); ctx.moveTo(v.X(gx), rect.y); ctx.lineTo(v.X(gx), rect.y + rect.h); ctx.stroke(); }
    for (var gy = Math.ceil(win.y0 * 2) / 2; gy <= win.y1; gy += 0.5) { ctx.beginPath(); ctx.moveTo(rect.x, v.Y(gy)); ctx.lineTo(rect.x + rect.w, v.Y(gy)); ctx.stroke(); }
